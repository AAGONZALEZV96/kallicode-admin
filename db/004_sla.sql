-- Función agregada de solo lectura por ciclo comercial (YYYY-MM) y tenant opcional
CREATE OR REPLACE FUNCTION admin.calcular_cumplimiento_sla_ciclo(
    p_ciclo     text,
    p_tenant_id text DEFAULT NULL
)
RETURNS TABLE (
    ciclo                text,
    tenant_id            text,
    plan_codigo          text,
    casos_totales        bigint,
    casos_evaluados      bigint,
    casos_dentro         bigint,
    casos_incumplidos    bigint,
    casos_en_riesgo      bigint,
    casos_en_curso       bigint,
    casos_sin_objetivo   bigint,
    cumplimiento_pct     numeric(5,2),
    bruto_total_h        numeric(12,2),
    transcurrido_total_h numeric(12,2)
) AS $$
#variable_conflict use_column
BEGIN
    IF p_ciclo IS NULL OR p_ciclo !~ '^\d{4}-\d{2}$' THEN
        RAISE EXCEPTION 'El ciclo debe tener formato YYYY-MM (recibido: %)',
            coalesce(p_ciclo, 'NULL')
            USING ERRCODE = '22023';
    END IF;

    RETURN QUERY
    WITH casos_ciclo AS (
        SELECT s.job_id
          FROM admin.sla_clock_segments s
         WHERE (p_tenant_id IS NULL OR s.tenant_id = p_tenant_id)
         GROUP BY s.job_id
        HAVING to_char(min(s.inicio), 'YYYY-MM') = p_ciclo
        UNION
        SELECT c.job_id
          FROM admin.sla_cases c
         WHERE to_char(c.iniciado_en, 'YYYY-MM') = p_ciclo
           AND (p_tenant_id IS NULL OR c.tenant_id = p_tenant_id)
        UNION
        SELECT jb.id AS job_id
          FROM core.jobs jb
         WHERE to_char(jb.creado_en, 'YYYY-MM') = p_ciclo
           AND (p_tenant_id IS NULL OR jb.tenant_id = p_tenant_id)
    ),
    evaluados AS (
        SELECT rc.*
          FROM casos_ciclo cc
          CROSS JOIN LATERAL admin.calcular_reloj_caso(cc.job_id) rc
    )
    SELECT p_ciclo,
           e.tenant_id,
           max(e.plan_codigo),
           count(*)::bigint,
           count(*) FILTER (WHERE e.resultado IN ('dentro', 'incumplido'))::bigint,
           count(*) FILTER (WHERE e.resultado = 'dentro')::bigint,
           count(*) FILTER (WHERE e.resultado = 'incumplido')::bigint,
           count(*) FILTER (WHERE e.resultado = 'en_riesgo')::bigint,
           count(*) FILTER (WHERE e.resultado = 'en_curso')::bigint,
           count(*) FILTER (WHERE e.resultado = 'sin_objetivo')::bigint,
           round(
               100.0 * count(*) FILTER (WHERE e.resultado = 'dentro')
               / nullif(count(*) FILTER (WHERE e.resultado IN ('dentro', 'incumplido')), 0),
               2
           )::numeric(5,2),
           coalesce(sum(e.bruto_h), 0.00)::numeric(12,2),
           coalesce(sum(e.transcurrido_h), 0.00)::numeric(12,2)
      FROM evaluados e
     GROUP BY e.tenant_id
     ORDER BY e.tenant_id;
END $$ LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = admin, core, pg_temp;

