-- -----------------------------------------------------------------------------
-- 3. Tramos cronológicos del reloj por caso (`admin.sla_clock_segments`)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS admin.sla_clock_segments (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   text        NOT NULL REFERENCES core.organizations(id),
    job_id      text        NOT NULL,
    ticket_id   text,
    etapa       text        NOT NULL,
    inicio      timestamptz NOT NULL,
    fin         timestamptz,                  -- NULL si el tramo sigue en curso
    computa     boolean     NOT NULL DEFAULT true,
    causa_pausa text,
    creado_en   timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT chk_causa_pausa CHECK (
        (computa IS TRUE AND causa_pausa IS NULL)
        OR (
            computa IS FALSE
            AND causa_pausa IS NOT NULL
            AND causa_pausa IN (
                'espera_firma_cliente',
                'escalado_humano',
                'ventana_mantenimiento',
                'indisponibilidad_proveedor_llm',
                'otro'
            )
        )
    ),
    CONSTRAINT chk_segment_window CHECK (fin IS NULL OR fin >= inicio)
);

-- Asegura `chk_causa_pausa` estricto (rechaza NULL cuando computa = false) en reaplicaciones
DO $$
BEGIN
    IF EXISTS (
        SELECT 1
          FROM pg_constraint c
          JOIN pg_class t ON t.oid = c.conrelid
          JOIN pg_namespace n ON n.oid = t.relnamespace
         WHERE n.nspname = 'admin'
           AND t.relname = 'sla_clock_segments'
           AND c.conname = 'chk_causa_pausa'
    ) THEN
        ALTER TABLE admin.sla_clock_segments DROP CONSTRAINT chk_causa_pausa;
    END IF;
    ALTER TABLE admin.sla_clock_segments
        ADD CONSTRAINT chk_causa_pausa CHECK (
            (computa IS TRUE AND causa_pausa IS NULL)
            OR (
                computa IS FALSE
                AND causa_pausa IS NOT NULL
                AND causa_pausa IN (
                    'espera_firma_cliente',
                    'escalado_humano',
                    'ventana_mantenimiento',
                    'indisponibilidad_proveedor_llm',
                    'otro'
                )
            )
        );
END $$;

CREATE INDEX IF NOT EXISTS slacs_job_inicio_ix
