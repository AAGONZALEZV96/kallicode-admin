-- Materializa el cálculo del reloj de un caso en `admin.sla_cases` (y sincroniza
-- tramos desde `core.job_transitions` cuando aún no existen en `sla_clock_segments`).
CREATE OR REPLACE FUNCTION admin.compute_sla_case(p_job_id text)
RETURNS admin.sla_cases AS $$
DECLARE
    j               record;
    rc              record;
    tr              record;
    fin_tramo       timestamptz;
    fin_caso        timestamptz;
    computa         boolean;
    causa           text;
    causa_seg       text;
    tiene_segmentos boolean := false;
    reglas_arr      text[] := '{}';
    iniciado        timestamptz;
    terminado       timestamptz;
    salida          admin.sla_cases;
BEGIN
    SELECT jb.id, jb.tenant_id, jb.ticket_id, jb.estado, jb.creado_en,
           jb.terminado_en, tk.numero, tk.etapa
      INTO j
      FROM core.jobs jb
      LEFT JOIN core.tickets tk ON tk.id = jb.ticket_id
     WHERE jb.id = p_job_id;

    SELECT EXISTS (
        SELECT 1 FROM admin.sla_clock_segments s WHERE s.job_id = p_job_id
    ) INTO tiene_segmentos;

    IF j.id IS NULL AND NOT tiene_segmentos THEN
        RETURN NULL;
    END IF;

    -- Si proviene de core.jobs y aún no hay tramos materializados, proyectarlos
    IF j.id IS NOT NULL AND NOT tiene_segmentos THEN
        fin_caso := coalesce(j.terminado_en, now());
        FOR tr IN
            SELECT jt.creado_en AS desde, jt.a_estado AS estado,
                   lead(jt.creado_en) OVER (ORDER BY jt.creado_en) AS hasta
              FROM core.job_transitions jt
             WHERE jt.job_id = p_job_id
             ORDER BY jt.creado_en
        LOOP
            fin_tramo := coalesce(tr.hasta, fin_caso);
            IF fin_tramo <= tr.desde THEN
                CONTINUE;
            END IF;

            causa := NULL;
            SELECT ps.motivo INTO causa
              FROM admin.sla_pause_states ps
             WHERE ps.estado_job = tr.estado AND ps.activa;

            computa := causa IS NULL;
            IF computa THEN
                causa_seg := NULL;
            ELSIF causa IN (
                'espera_firma_cliente',
                'escalado_humano',
                'ventana_mantenimiento',
                'indisponibilidad_proveedor_llm',
                'otro'
            ) THEN
                causa_seg := causa;
            ELSE
                causa_seg := 'otro';
            END IF;

            INSERT INTO admin.sla_clock_segments
                (tenant_id, job_id, ticket_id, etapa, inicio, fin, computa, causa_pausa)
            VALUES (
                j.tenant_id,
                j.id,
                j.ticket_id,
                tr.estado,
                tr.desde,
                CASE WHEN tr.hasta IS NOT NULL OR j.terminado_en IS NOT NULL
                     THEN fin_tramo ELSE NULL END,
                computa,
                causa_seg
            );
        END LOOP;
    END IF;

    SELECT * INTO rc FROM admin.calcular_reloj_caso(p_job_id);
    IF NOT FOUND THEN
        RETURN NULL;
    END IF;

    SELECT ARRAY(SELECT jsonb_array_elements_text(rc.reglas_aplicadas))
      INTO reglas_arr;

    IF j.id IS NOT NULL THEN
        iniciado := j.creado_en;
        terminado := j.terminado_en;
    ELSE
        SELECT min(s.inicio),
               CASE WHEN bool_or(s.fin IS NULL) THEN NULL ELSE max(s.fin) END
          INTO iniciado, terminado
          FROM admin.sla_clock_segments s
         WHERE s.job_id = p_job_id;
    END IF;

    INSERT INTO admin.sla_cases
        (job_id, tenant_id, ticket_id, ticket_numero, plan_codigo, etapa_final,
         objetivo_h, bruto_h, transcurrido_h, resultado, tramos, reglas,
         iniciado_en, terminado_en, calculado_en)
    VALUES (
        p_job_id,
        rc.tenant_id,
        j.ticket_id,
        j.numero,
        rc.plan_codigo,
        j.etapa,
        rc.objetivo_h,
        rc.bruto_h,
        rc.transcurrido_h,
        rc.resultado,
        rc.tramos,
        coalesce(reglas_arr, '{}'),
        iniciado,
        terminado,
        now()
    )
    ON CONFLICT (job_id) DO UPDATE SET
        objetivo_h     = excluded.objetivo_h,
        bruto_h        = excluded.bruto_h,
        transcurrido_h = excluded.transcurrido_h,
        resultado      = excluded.resultado,
        tramos         = excluded.tramos,
        reglas         = excluded.reglas,
        etapa_final    = excluded.etapa_final,
        terminado_en   = excluded.terminado_en,
        calculado_en   = now()
    RETURNING * INTO salida;

    RETURN salida;
END $$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = admin, core, pg_temp;

