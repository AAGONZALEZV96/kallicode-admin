-- Recalcula los casos de una ventana y materializa `admin.agg_sla_compliance`.
CREATE OR REPLACE FUNCTION admin.refresh_sla(
    p_dias   int DEFAULT 95,
    p_forzar boolean DEFAULT false
)
RETURNS bigint AS $$
DECLARE
    r        record;
    c        record;
    n        bigint := 0;
    n_agg    bigint := 0;
    v_ciclos text[];
    v_ciclo  text;
BEGIN
    FOR r IN
        SELECT candidatos.job_id
          FROM (
              SELECT j.id AS job_id, j.terminado_en AS terminado
                FROM core.jobs j
               WHERE j.creado_en >= current_date - p_dias
              UNION ALL
              SELECT s.job_id,
                     CASE WHEN bool_or(s.fin IS NULL) THEN NULL ELSE max(s.fin) END AS terminado
                FROM admin.sla_clock_segments s
               GROUP BY s.job_id
              HAVING min(s.inicio) >= current_date - p_dias
          ) AS candidatos
         GROUP BY candidatos.job_id
         HAVING p_forzar
             OR bool_or(candidatos.terminado IS NULL)
             OR NOT EXISTS (
                 SELECT 1 FROM admin.sla_cases sc
                  WHERE sc.job_id = candidatos.job_id
                    AND sc.terminado_en IS NOT NULL
             )
    LOOP
        PERFORM admin.compute_sla_case(r.job_id);
        n := n + 1;
    END LOOP;

    SELECT ARRAY(
        SELECT DISTINCT to_char(sc.iniciado_en, 'YYYY-MM')
          FROM admin.sla_cases sc
         WHERE sc.iniciado_en >= current_date - p_dias
    ) INTO v_ciclos;

    IF v_ciclos IS NOT NULL AND coalesce(array_length(v_ciclos, 1), 0) > 0 THEN
        FOREACH v_ciclo IN ARRAY v_ciclos LOOP
            DELETE FROM admin.agg_sla_compliance WHERE ciclo = v_ciclo;
            FOR c IN
                SELECT * FROM admin.calcular_cumplimiento_sla_ciclo(v_ciclo, NULL)
            LOOP
                INSERT INTO admin.agg_sla_compliance
                    (ciclo, tenant_id, plan_codigo, objetivo_h,
                     casos_totales, casos_evaluados, casos_dentro,
                     casos_incumplidos, casos_en_riesgo, casos_en_curso,
                     casos_sin_objetivo, cumplimiento_pct,
                     bruto_total_h, transcurrido_total_h, actualizado_en)
                VALUES (
                    c.ciclo,
                    c.tenant_id,
                    c.plan_codigo,
                    (SELECT t.objetivo_h FROM admin.sla_targets t
                      WHERE t.plan_codigo = c.plan_codigo
                        AND t.etapa IN ('total_e2e', '*')
                        AND t.activo = true
                      ORDER BY (t.etapa = 'total_e2e') DESC, t.vigente_desde DESC
                      LIMIT 1),
                    c.casos_totales::int,
                    c.casos_evaluados::int,
                    c.casos_dentro::int,
                    c.casos_incumplidos::int,
                    c.casos_en_riesgo::int,
                    c.casos_en_curso::int,
                    c.casos_sin_objetivo::int,
                    c.cumplimiento_pct,
                    c.bruto_total_h,
                    c.transcurrido_total_h,
                    now()
                )
                ON CONFLICT (ciclo, tenant_id) DO UPDATE SET
                    plan_codigo          = excluded.plan_codigo,
                    objetivo_h           = excluded.objetivo_h,
                    casos_totales        = excluded.casos_totales,
                    casos_evaluados      = excluded.casos_evaluados,
                    casos_dentro         = excluded.casos_dentro,
                    casos_incumplidos    = excluded.casos_incumplidos,
                    casos_en_riesgo      = excluded.casos_en_riesgo,
                    casos_en_curso       = excluded.casos_en_curso,
                    casos_sin_objetivo   = excluded.casos_sin_objetivo,
                    cumplimiento_pct     = excluded.cumplimiento_pct,
                    bruto_total_h        = excluded.bruto_total_h,
                    transcurrido_total_h = excluded.transcurrido_total_h,
                    actualizado_en       = now();
                n_agg := n_agg + 1;
            END LOOP;
        END LOOP;
    END IF;

    INSERT INTO admin.aggregate_state (agregado, refreshed_at, rows_total, status)
         VALUES ('sla_cases', now(), n, 'ok')
    ON CONFLICT (agregado) DO UPDATE
        SET refreshed_at = now(), rows_total = n, status = 'ok', error = NULL;

    INSERT INTO admin.aggregate_state (agregado, refreshed_at, rows_total, status)
         VALUES ('agg_sla_compliance', now(), n_agg, 'ok')
    ON CONFLICT (agregado) DO UPDATE
        SET refreshed_at = now(), rows_total = n_agg, status = 'ok', error = NULL;

    RETURN n;
END $$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = admin, core, pg_temp;

