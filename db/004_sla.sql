-- 6. Funciones PL/pgSQL deterministas de cálculo de reloj y cumplimiento
-- -----------------------------------------------------------------------------

-- Función pura de lectura: calcula el reloj de un caso a partir de los tramos
-- registrados en `admin.sla_clock_segments` (o, si aún no existen, desde
-- `core.job_transitions` + `admin.sla_pause_states`).
CREATE OR REPLACE FUNCTION admin.calcular_reloj_caso(p_job_id text)
RETURNS TABLE (
    job_id           text,
    tenant_id        text,
    plan_codigo      text,
    objetivo_h       numeric(8,2),
    transcurrido_h   numeric(10,2),
    bruto_h          numeric(10,2),
    resultado        text,
    tramos           jsonb,
    reglas_aplicadas jsonb
) AS $$
#variable_conflict use_column
DECLARE
    v_job_existe      boolean := false;
    v_job_tenant      text;
    v_job_creado_en   timestamptz;
    v_job_terminado   timestamptz;
    v_tiene_segmentos boolean := false;
    v_seg_abierto     boolean := false;
    v_seg_min_inicio  timestamptz;
    v_seg_max_fin     timestamptz;
    v_seg_tenant      text;
    v_tenant_id       text;
    v_iniciado_en     timestamptz;
    v_terminado_en    timestamptz;
    v_fin_caso        timestamptz;
    v_plan_cod        text;
    v_objetivo        numeric(8,2);
    v_riesgo_pct      numeric(5,2) := 80.00;
    v_bruto           numeric := 0;
    v_contado         numeric := 0;
    v_tramos          jsonb := '[]'::jsonb;
    v_reglas          text[] := '{}';
    v_res             text;
    v_min_inicio      timestamptz;
    v_max_fin         timestamptz;
    v_seg_h           numeric;
    v_causa           text;
    v_computa         boolean;
    v_fin_tramo       timestamptz;
    tr                record;
BEGIN
    SELECT jb.tenant_id, jb.creado_en, jb.terminado_en
      INTO v_job_tenant, v_job_creado_en, v_job_terminado
      FROM core.jobs jb
     WHERE jb.id = p_job_id;
    v_job_existe := FOUND;

    SELECT count(*) > 0,
           bool_or(s.fin IS NULL),
           min(s.inicio),
           max(s.fin),
           min(s.tenant_id)
      INTO v_tiene_segmentos, v_seg_abierto, v_seg_min_inicio, v_seg_max_fin, v_seg_tenant
      FROM admin.sla_clock_segments s
     WHERE s.job_id = p_job_id;

    IF NOT v_job_existe AND NOT v_tiene_segmentos THEN
        RETURN;
    END IF;

    v_tenant_id := coalesce(v_job_tenant, v_seg_tenant);
    v_iniciado_en := coalesce(v_job_creado_en, v_seg_min_inicio);

    IF v_job_existe THEN
        v_terminado_en := v_job_terminado;
    ELSIF NOT v_seg_abierto THEN
        v_terminado_en := v_seg_max_fin;
    ELSE
        v_terminado_en := NULL;
    END IF;

    v_fin_caso := coalesce(v_terminado_en, now());

    SELECT s.plan_codigo INTO v_plan_cod
      FROM core.subscriptions s
     WHERE s.tenant_id = v_tenant_id
       AND s.estado <> 'finalizada'
     ORDER BY s.inicia_el DESC
     LIMIT 1;

    IF v_plan_cod IS NULL THEN
        SELECT cs.plan_codigo INTO v_plan_cod
          FROM admin.agg_customer_state cs
         WHERE cs.tenant_id = v_tenant_id
         LIMIT 1;
    END IF;

    SELECT t.objetivo_h, t.riesgo_pct
      INTO v_objetivo, v_riesgo_pct
      FROM admin.sla_targets t
     WHERE t.plan_codigo = v_plan_cod
       AND t.etapa IN ('total_e2e', '*')
       AND t.activo = true
       AND t.vigente_desde <= v_iniciado_en::date
     ORDER BY (t.etapa = 'total_e2e') DESC, t.vigente_desde DESC
     LIMIT 1;

    IF v_tiene_segmentos THEN
        FOR tr IN
            SELECT s.inicio,
                   coalesce(s.fin, v_fin_caso) AS fin_ef,
                   s.etapa,
                   s.computa,
                   s.causa_pausa
              FROM admin.sla_clock_segments s
             WHERE s.job_id = p_job_id
             ORDER BY s.inicio, s.id
        LOOP
            IF tr.fin_ef <= tr.inicio THEN
                CONTINUE;
            END IF;

            v_seg_h := extract(epoch FROM tr.fin_ef - tr.inicio) / 3600.0;
            IF tr.computa THEN
                v_contado := v_contado + v_seg_h;
            ELSIF tr.causa_pausa IS NOT NULL AND NOT (tr.causa_pausa = ANY(v_reglas)) THEN
                v_reglas := v_reglas || tr.causa_pausa;
            END IF;

            v_min_inicio := least(coalesce(v_min_inicio, tr.inicio), tr.inicio);
            v_max_fin := greatest(coalesce(v_max_fin, tr.fin_ef), tr.fin_ef);

            v_tramos := v_tramos || jsonb_build_object(
                'inicio', tr.inicio,
                'fin', tr.fin_ef,
                'etapa', tr.etapa,
                'computa', tr.computa,
                'causa_pausa', tr.causa_pausa,
                'horas', round(v_seg_h, 3)
            );
        END LOOP;

        IF v_min_inicio IS NOT NULL AND v_max_fin IS NOT NULL THEN
            v_bruto := extract(epoch FROM v_max_fin - v_min_inicio) / 3600.0;
        END IF;
    ELSE
        FOR tr IN
            SELECT jt.creado_en AS desde,
                   jt.a_estado AS estado,
                   lead(jt.creado_en) OVER (ORDER BY jt.creado_en) AS hasta
              FROM core.job_transitions jt
             WHERE jt.job_id = p_job_id
             ORDER BY jt.creado_en
        LOOP
            v_fin_tramo := coalesce(tr.hasta, v_fin_caso);
            IF v_fin_tramo <= tr.desde THEN
                CONTINUE;
            END IF;

            v_causa := NULL;
            SELECT ps.motivo INTO v_causa
              FROM admin.sla_pause_states ps
             WHERE ps.estado_job = tr.estado AND ps.activa;

            v_computa := v_causa IS NULL;
            IF NOT v_computa AND NOT (v_causa = ANY(v_reglas)) THEN
                v_reglas := v_reglas || v_causa;
            END IF;

            v_seg_h := extract(epoch FROM v_fin_tramo - tr.desde) / 3600.0;
            IF v_computa THEN
                v_contado := v_contado + v_seg_h;
            END IF;

            v_min_inicio := least(coalesce(v_min_inicio, tr.desde), tr.desde);
            v_max_fin := greatest(coalesce(v_max_fin, v_fin_tramo), v_fin_tramo);

            v_tramos := v_tramos || jsonb_build_object(
                'inicio', tr.desde,
                'fin', v_fin_tramo,
                'etapa', tr.estado,
                'computa', v_computa,
                'causa_pausa', v_causa,
                'horas', round(v_seg_h, 3)
            );
        END LOOP;

        IF jsonb_array_length(v_tramos) = 0 THEN
            v_bruto := greatest(0, extract(epoch FROM v_fin_caso - v_iniciado_en) / 3600.0);
            v_contado := v_bruto;
        ELSIF v_min_inicio IS NOT NULL AND v_max_fin IS NOT NULL THEN
            v_bruto := extract(epoch FROM v_max_fin - v_min_inicio) / 3600.0;
        END IF;
    END IF;

    IF v_objetivo IS NULL THEN
        v_res := 'sin_objetivo';
    ELSIF v_terminado_en IS NULL THEN
        v_res := CASE
            WHEN v_contado > v_objetivo THEN 'incumplido'
            WHEN v_contado >= v_objetivo * (coalesce(v_riesgo_pct, 80.00) / 100.0) THEN 'en_riesgo'
            ELSE 'en_curso'
        END;
    ELSE
        v_res := CASE
            WHEN v_contado > v_objetivo THEN 'incumplido'
            ELSE 'dentro'
        END;
    END IF;

    RETURN QUERY SELECT
        p_job_id,
        v_tenant_id,
        v_plan_cod,
        v_objetivo,
        round(v_contado, 2)::numeric(10,2),
        round(v_bruto, 2)::numeric(10,2),
        v_res,
        v_tramos,
        to_jsonb(v_reglas);
END $$ LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = admin, core, pg_temp;

