-- -----------------------------------------------------------------------------
-- 1. Objetivos por plan comercial y etapa (`admin.sla_targets`)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS admin.sla_targets (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_codigo   text NOT NULL REFERENCES core.plans(codigo),
    etapa         text NOT NULL,              -- '*' / 'total_e2e' = extremo a extremo
    objetivo_h    numeric(8,2) NOT NULL,
    riesgo_pct    numeric(5,2) NOT NULL DEFAULT 80.00,
    vigente_desde date NOT NULL DEFAULT current_date,
    activo        boolean NOT NULL DEFAULT true,
    creado_en     timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT slat_obj_chk    CHECK (objetivo_h > 0),
    CONSTRAINT slat_riesgo_chk CHECK (riesgo_pct BETWEEN 1 AND 100),
    CONSTRAINT slat_etapa_chk  CHECK (etapa IN ('*', 'total_e2e', 'triage', 'design',
                                                'build', 'qa', 'security', 'deploy')),
    CONSTRAINT sla_targets_plan_etapa_uq UNIQUE (plan_codigo, etapa)
);

-- Evolución idempotente si `admin.sla_targets` existía con el DDL previo
DO $$
DECLARE
    pk_name text;
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
         WHERE table_schema = 'admin'
           AND table_name = 'sla_targets'
           AND column_name = 'id'
    ) THEN
        ALTER TABLE admin.sla_targets
            ADD COLUMN id bigint GENERATED BY DEFAULT AS IDENTITY;
    END IF;

    ALTER TABLE admin.sla_targets
        ADD COLUMN IF NOT EXISTS activo boolean NOT NULL DEFAULT true;
    ALTER TABLE admin.sla_targets
        ADD COLUMN IF NOT EXISTS creado_en timestamptz NOT NULL DEFAULT now();

    SELECT c.conname INTO pk_name
      FROM pg_constraint c
      JOIN pg_class t ON t.oid = c.conrelid
      JOIN pg_namespace n ON n.oid = t.relnamespace
     WHERE n.nspname = 'admin'
       AND t.relname = 'sla_targets'
       AND c.contype = 'p';

    IF pk_name IS NOT NULL AND NOT EXISTS (
        SELECT 1
          FROM pg_constraint c
          JOIN pg_class t ON t.oid = c.conrelid
          JOIN pg_namespace n ON n.oid = t.relnamespace
          JOIN pg_attribute a ON a.attrelid = t.oid AND a.attnum = ANY(c.conkey)
         WHERE n.nspname = 'admin'
           AND t.relname = 'sla_targets'
           AND c.contype = 'p'
           AND array_length(c.conkey, 1) = 1
           AND a.attname = 'id'
    ) THEN
        EXECUTE format('ALTER TABLE admin.sla_targets DROP CONSTRAINT %I', pk_name);
        ALTER TABLE admin.sla_targets ADD PRIMARY KEY (id);
    ELSIF pk_name IS NULL THEN
        ALTER TABLE admin.sla_targets ADD PRIMARY KEY (id);
    END IF;

    IF EXISTS (
        SELECT 1
          FROM pg_constraint c
          JOIN pg_class t ON t.oid = c.conrelid
          JOIN pg_namespace n ON n.oid = t.relnamespace
         WHERE n.nspname = 'admin'
           AND t.relname = 'sla_targets'
           AND c.conname = 'slat_etapa_chk'
    ) THEN
        ALTER TABLE admin.sla_targets DROP CONSTRAINT slat_etapa_chk;
    END IF;

    ALTER TABLE admin.sla_targets
        ADD CONSTRAINT slat_etapa_chk CHECK (
            etapa IN ('*', 'total_e2e', 'triage', 'design',
                      'build', 'qa', 'security', 'deploy')
        );

    IF NOT EXISTS (
        SELECT 1
          FROM pg_constraint c
          JOIN pg_class t ON t.oid = c.conrelid
          JOIN pg_namespace n ON n.oid = t.relnamespace
         WHERE n.nspname = 'admin'
           AND t.relname = 'sla_targets'
           AND c.conname = 'sla_targets_plan_etapa_uq'
    ) THEN
        ALTER TABLE admin.sla_targets
            ADD CONSTRAINT sla_targets_plan_etapa_uq UNIQUE (plan_codigo, etapa);
    END IF;
END $$;

